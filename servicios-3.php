  (function(){
    const track = document.querySelector('.srv-furniture__track');
    if(!track) return;
    const cards = Array.from(track.querySelectorAll('.srv-furniture__card'));
    const slider = document.querySelector('.srv-furniture__slider');
    let idx = 0;
    let isDown = false, startX, scrollLeft;

    function getCardWidth(){
      if(!cards.length) return 0;
      const style = getComputedStyle(track);
      const gap = parseInt(style.gap) || 24;
      return cards[0].offsetWidth + gap;
    }

    function getVisibleCount(){
      const w = window.innerWidth;
      if(w <= 520) return 1;
      if(w <= 720) return 2;
      if(w <= 980) return 3;
      return 4;
    }

    function update(){
      const v = getVisibleCount();
      const max = Math.max(cards.length - v, 0);
      if(idx > max) idx = max;
      if(idx < 0) idx = 0;
      const cw = getCardWidth();
      track.style.transform = `translateX(-${idx * cw}px)`;

      /* Aplicar opacidad a cards parcialmente visibles */
      cards.forEach((card, i) => {
        if(i < idx || i >= idx + v){
          card.style.opacity = '0.35';
          card.style.pointerEvents = 'none';
        } else if(i === idx || i === idx + v - 1){
          /* Primer y último visible: semi-transparentes en los bordes */
          card.style.opacity = '1';
          card.style.pointerEvents = 'auto';
        } else {
          card.style.opacity = '1';
          card.style.pointerEvents = 'auto';
        }
      });

      /* Las cards justo fuera del rango visible tienen opacidad parcial */
      if(idx > 0 && cards[idx - 1]){
        cards[idx - 1].style.opacity = '0.35';
      }
      if(idx + v < cards.length && cards[idx + v]){
        cards[idx + v].style.opacity = '0.35';
      }
    }

    /* Auto-slide cada 4 segundos */
    let autoInterval = setInterval(()=>{
      const v = getVisibleCount();
      const max = Math.max(cards.length - v, 0);
      idx = idx >= max ? 0 : idx + 1;
      update();
    }, 4000);

    function resetAuto(){
      clearInterval(autoInterval);
      autoInterval = setInterval(()=>{
        const v = getVisibleCount();
        const max = Math.max(cards.length - v, 0);
        idx = idx >= max ? 0 : idx + 1;
        update();
      }, 4000);
    }

    /* Touch/drag support */
    slider.addEventListener('mousedown', (e)=>{
      isDown = true;
      startX = e.pageX;
      slider.style.cursor = 'grabbing';
    });
    slider.addEventListener('mouseleave', ()=>{ isDown = false; slider.style.cursor = ''; });
    slider.addEventListener('mouseup', ()=>{ isDown = false; slider.style.cursor = ''; });
    slider.addEventListener('mousemove', (e)=>{
      if(!isDown) return;
      e.preventDefault();
      const diff = e.pageX - startX;
      if(Math.abs(diff) > 60){
        if(diff < 0) idx++;
        else idx--;
        update();
        resetAuto();
        isDown = false;
        slider.style.cursor = '';
      }
    });

    /* Touch events */
    let touchStartX = 0;
    slider.addEventListener('touchstart', (e)=>{ touchStartX = e.touches[0].clientX; }, {passive:true});
    slider.addEventListener('touchend', (e)=>{
      const diff = e.changedTouches[0].clientX - touchStartX;
      if(Math.abs(diff) > 50){
        if(diff < 0) idx++;
        else idx--;
        update();
        resetAuto();
      }
    });

    window.addEventListener('resize', update);
    update();
  })();
